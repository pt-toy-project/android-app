    fun forBlock(hero: Hero, blockId: String, kind: DayKind, source: HistoricalSource): List<DayQuest> {
        val profile = profiles.getValue(hero.id)
        val steps: List<Pair<String, String>> = when (kind) {
            DayKind.WORK -> profile.work.mapIndexed { i, text -> text to listOf("준비 2분", "집중 8분 · 필요하면 휴식", "정리 5분")[i] }
            DayKind.LEARN -> profile.learn.map { it to "5분" }
            DayKind.REFLECT -> profile.reflect.map { it to "2분" }
            DayKind.WAKE -> listOf("몸 상태를 살피고 오늘의 첫 행동을 정한다" to "2분", "내 생활에 맞는 아침 식사를 챙긴다" to "식사 1회")
            DayKind.MEAL -> listOf("점심 식사를 하고 몸 상태를 살핀다" to "식사 1회", "식사 뒤 잠시 쉬고 다음 활동을 준비한다" to "5분")
            DayKind.WALK -> listOf("무리 없이 걸을 안전한 길을 정한다" to "2분", DayEditorialProfiles.forHero(hero.id).walking to "10분")
            DayKind.REST -> listOf("내 일정에 맞춰 저녁 식사를 챙긴다" to "식사 1회", DayEditorialProfiles.forHero(hero.id).rest to "5분")
            DayKind.SLEEP -> listOf("내일 필요한 물건을 정리한다" to "3분", "화면을 내려놓고 내가 정한 취침 시간에 쉰다" to "취침 준비 10분")
        }
        return steps.mapIndexed { index, (instruction, measure) ->
            DayQuest("${blockId}_q${index + 1}", when (kind) {
                DayKind.WAKE -> if (index == 0) "하루 준비" else "아침 식사"
                DayKind.MEAL -> if (index == 0) "점심 식사" else "식사 후 휴식"
                DayKind.REST -> if (index == 0) "저녁 식사" else "휴식"
                DayKind.SLEEP -> if (index == 0) "내일 준비" else "취침 준비"
                DayKind.WALK -> if (index == 0) "안전한 길 선택" else "걷고 관찰하기"
                else -> instruction
            }, instruction, measure, source)
        }
    }
